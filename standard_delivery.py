def calculate_delivery_fee(delivery_type, coupon):

    if delivery_type == "standard":
        fee = 30

    elif delivery_type == "express":
        fee = 70

    else:
        return "Invalid delivery type"

    if coupon == "VALID":
        fee = 0

    return fee


# Test cases
print("Standard:", calculate_delivery_fee("standard", "INVALID"))

print("Express:", calculate_delivery_fee("express", "INVALID"))

print("Standard with coupon:", calculate_delivery_fee("standard", "VALID"))

